import numpy as np, onnxruntime as ort
from PIL import Image, ImageDraw
from IPython.display import display

MODEL = "/content/drive/MyDrive/prepared/quantization/circuitguard_int8/weights/best.onnx"
CONF = 0.5
CLASSES = ["open", "short", "mousebite", "spur", "copper", "pin-hole"]
session = ort.InferenceSession(MODEL, providers=["CPUExecutionProvider"])

def preprocess(image):
    original = image.size
    scale = min(640 / image.width, 640 / image.height)
    nw, nh = round(image.width * scale), round(image.height * scale)
    resized = image.resize((nw, nh), Image.Resampling.BILINEAR)
    canvas = Image.new("RGB", (640, 640), (114, 114, 114))
    left, top = (640 - nw) // 2, (640 - nh) // 2
    canvas.paste(resized, (left, top))
    arr = np.asarray(canvas, dtype=np.float32) / 255.0
    return np.transpose(arr, (2, 0, 1))[None, ...], original, scale, left, top

def nms(boxes, scores, threshold=0.45):
    order = np.argsort(scores)[::-1]
    keep = []
    while len(order):
        i = order[0]; keep.append(i)
        rest = order[1:]
        if len(rest) == 0: break
        xx1 = np.maximum(boxes[i, 0], boxes[rest, 0])
        yy1 = np.maximum(boxes[i, 1], boxes[rest, 1])
        xx2 = np.minimum(boxes[i, 2], boxes[rest, 2])
        yy2 = np.minimum(boxes[i, 3], boxes[rest, 3])
        inter = np.maximum(0, xx2 - xx1) * np.maximum(0, yy2 - yy1)
        area_i = (boxes[i, 2] - boxes[i, 0]) * (boxes[i, 3] - boxes[i, 1])
        area_r = (boxes[rest, 2] - boxes[rest, 0]) * (boxes[rest, 3] - boxes[rest, 1])
        iou = inter / np.maximum(area_i + area_r - inter, 1e-7)
        order = rest[iou <= threshold]
    return keep

def detect(image):
    tensor, original, scale, left, top = preprocess(image)
    out = session.run(None, {"images": tensor})[0][0].T
    sc_all = out[:, 4:10]
    cls = sc_all.argmax(axis=1)
    sc = sc_all.max(axis=1)
    v = sc >= CONF
    out, sc, cls = out[v], sc[v], cls[v]
    b = out[:, :4].copy()
    b[:, 0] = out[:, 0] - out[:, 2] / 2
    b[:, 1] = out[:, 1] - out[:, 3] / 2
    b[:, 2] = out[:, 0] + out[:, 2] / 2
    b[:, 3] = out[:, 1] + out[:, 3] / 2
    dets = []
    for c in np.unique(cls):
        idxs = np.where(cls == c)[0]
        for k in nms(b[idxs], sc[idxs]):
            i = idxs[k]
            x1, y1, x2, y2 = b[i]
            x1 = max(0, min(original[0], (x1 - left) / scale))
            x2 = max(0, min(original[0], (x2 - left) / scale))
            y1 = max(0, min(original[1], (y1 - top) / scale))
            y2 = max(0, min(original[1], (y2 - top) / scale))
            dets.append((CLASSES[int(cls[i])], float(sc[i]),
                         [round(float(x1), 1), round(float(y1), 1), round(float(x2), 1), round(float(y2), 1)]))
    return dets

